def grid_rows(S, x_min, x_max, y_min, y_max, tol=6):
    """cluster text cells into rows (by y) within a band; returns list of rows sorted by x"""
    cells=[(pos(el,tr)[1],pos(el,tr)[0],el) for el,tr in S.els if text_of(el).strip() and x_min<=pos(el,tr)[0]<=x_max and y_min<=pos(el,tr)[1]<=y_max]
    cells.sort(key=lambda c:(c[0],c[1])); rows=[]
    for c in cells:
        if rows and abs(c[0]-rows[-1][0][0])<=tol: rows[-1].append(c)
        else: rows.append([c])
    return [sorted(r,key=lambda c:c[1]) for r in rows]

